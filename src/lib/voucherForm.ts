import type { PaymentDetailInput, Voucher, VoucherInput, VoucherPreview } from '../api/contract.gen'
import { compareDecimal, isPositiveAmount } from './decimal'

/**
 * Voucher editor state ↔ VoucherInput (H9–H12; backlog P7.2-FE-05/06). Pure functions so they are unit-tested: the
 * editor keeps strings as typed; only complete lines are sent; totals, difference and warnings come from
 * POST /vouchers/calculate, never from here.
 */
export type VoucherKind = VoucherInput['entry_type']

export interface VoucherLineState {
  key: string
  ledgerId: number | null
  ledgerLabel: string
  debit: string
  credit: string
  amount: string
  line_narration: string
  against_reference: string
}

export interface VoucherFormState {
  type: VoucherKind
  date: string
  reference: string
  narration: string
  template_key: string
  payment: {
    money_account_id: string; counter_money_account_id: string; method: PaymentDetailInput['method']; payee_text: string
    cheque_number: string; cheque_date: string; transaction_reference: string; bank_charge: string
  }
  lines: VoucherLineState[]
}

let seq = 0
export const newLine = (over: Partial<VoucherLineState> = {}): VoucherLineState => ({
  key: `l${++seq}`, ledgerId: null, ledgerLabel: '', debit: '', credit: '', amount: '', line_narration: '', against_reference: '', ...over,
})

export function emptyVoucher(type: VoucherKind, date: string): VoucherFormState {
  return {
    type, date, reference: '', narration: '', template_key: '',
    payment: { money_account_id: '', counter_money_account_id: '', method: type === 'contra' ? 'cash' : 'cash', payee_text: '', cheque_number: '', cheque_date: '',
      transaction_reference: '', bank_charge: '' },
    lines: type === 'journal' ? [newLine(), newLine()] : [newLine()],
  }
}

/** A line the API can take: a ledger and, for a journal, exactly one positive side; otherwise a positive amount. */
export function isComplete(type: VoucherKind, l: VoucherLineState): boolean {
  if (!l.ledgerId) return false
  if (type !== 'journal') return isPositiveAmount(l.amount)
  return isPositiveAmount(l.debit) !== isPositiveAmount(l.credit)
}

const opt = (v: string) => (v.trim() === '' ? null : v.trim())

export function toVoucherInput(s: VoucherFormState, action: VoucherInput['action'], confirmBackdated = false): VoucherInput {
  const lines = s.lines.filter((l) => isComplete(s.type, l)).map((l) => {
    const base = { ledger_id: l.ledgerId!, line_narration: opt(l.line_narration), against_reference: opt(l.against_reference) }
    if (s.type !== 'journal') return { ...base, amount: l.amount.trim() }
    return isPositiveAmount(l.debit) ? { ...base, debit: l.debit.trim() } : { ...base, credit: l.credit.trim() }
  })
  const input: VoucherInput = { entry_type: s.type, action, date: s.date, reference: opt(s.reference), narration: opt(s.narration), template_key: opt(s.template_key), lines }
  if (s.type !== 'journal') {
    const p = s.payment
    input.payment = {
      money_account_id: Number(p.money_account_id), method: p.method, payee_text: opt(p.payee_text), cheque_number: opt(p.cheque_number), cheque_date: opt(p.cheque_date),
      transaction_reference: opt(p.transaction_reference), ...(isPositiveAmount(p.bank_charge) ? { bank_charge: p.bank_charge.trim() } : {}),
      ...(s.type === 'contra' && p.counter_money_account_id ? { counter_money_account_id: Number(p.counter_money_account_id) } : {}),
    }
  }
  if (confirmBackdated) input.confirm_backdated = true
  return input
}

/** Enough to ask the server: a date, (for cash vouchers) the account, and complete lines — two for a journal (a debit and a credit), one otherwise. */
export function readyToCalculate(s: VoucherFormState): boolean {
  if (!s.date) return false
  if (s.type !== 'journal' && !s.payment.money_account_id) return false
  return s.lines.filter((l) => isComplete(s.type, l)).length >= (s.type === 'journal' ? 2 : 1)
}

/**
 * "Put difference on last line" (H9): a new line with the server's difference on the short side, to which the user
 * then picks a ledger. Null when balanced or there is no preview.
 */
export function differenceLine(preview: VoucherPreview | null): VoucherLineState | null {
  if (!preview || preview.balanced || compareDecimal(preview.difference, '0') === 0) return null
  return compareDecimal(preview.total_debit, preview.total_credit) > 0 ? newLine({ credit: preview.difference }) : newLine({ debit: preview.difference })
}

/**
 * Editor state from a saved voucher (edit a draft, duplicate). A cash voucher's own account line and the bank-charge
 * line are generated by the server, so only the lines the user entered come back: everything but the account's
 * ledger and the line narrated "Bank charge".
 */
export function fromVoucher(v: Voucher, accountLedgerId?: number, date?: string): VoucherFormState {
  const type = (['journal', 'payment', 'receipt', 'contra'].includes(v.entry_type) ? v.entry_type : 'journal') as VoucherKind
  const p = (v.payment ?? null) as null | { money_account: { id: number }; counter_money_account?: { id: number } | null; method: PaymentDetailInput['method']; bank_charge: string
    cheque_number: string | null; cheque_date: string | null; transaction_reference: string | null; payee_text?: string | null }
  const s = emptyVoucher(type, date ?? v.entry_date)
  s.reference = v.reference ?? ''
  s.narration = v.narration ?? ''
  if (p) {
    s.payment = { ...s.payment, money_account_id: String(p.money_account.id), method: p.method, cheque_number: p.cheque_number ?? '', cheque_date: p.cheque_date ?? '',
      transaction_reference: p.transaction_reference ?? '', payee_text: p.payee_text ?? '', bank_charge: p.bank_charge && p.bank_charge !== '0.00' ? p.bank_charge : '' }
  }
  const entered = (v.lines ?? []).filter((l) => type === 'journal' || (l.ledger_id !== accountLedgerId && l.line_narration !== 'Bank charge'))
  s.lines = entered.map((l) => newLine({
    ledgerId: l.ledger_id, ledgerLabel: `${l.ledger_code} · ${l.ledger_name}`, line_narration: l.line_narration ?? '', against_reference: l.against_reference ?? '',
    ...(type === 'journal' ? { debit: l.debit !== '0.00' ? l.debit : '', credit: l.credit !== '0.00' ? l.credit : '' }
      : { amount: type === 'receipt' ? l.credit : l.debit }),
  }))
  if (s.lines.length === 0) s.lines = emptyVoucher(type, s.date).lines
  return s
}
